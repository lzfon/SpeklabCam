# SpekLab 相机 · 参数说明

## 引言：先分清两层

- 冲印（引擎）：把数字底片当成真负片去放印。颗粒、光晕、滤色、纸面都在这一层，输出是「已经洗出来的一张照片」。
- 调色（App 侧）：在这张成片上做二级校正。色温、对比、曲线、HSL 在这一层。

分层意义：放大机滤镜（Y/M）和调色的色温/色调不是一回事。前者是物理减色法，在冲印阶段改变三通道的曝光量；后者是在成片像素上做偏移，不改变底片曝光。同一个偏色，用滤镜修和用色温修，出来的颗粒、密度、层次都不一样。

# 一、冲印

## 1、胶片模拟与胶片前曲线

**1.1 胶片模拟（总开关）**

冲印页最顶部。开着，照片走完整胶片流程：负片曝光、乳剂颗粒、光晕、放大机滤色、相纸纸面都在；关掉后直接数字调色，下面「画幅与配光」「曝光与测光」「场景宽容度」「镜头滤镜」整组隐藏，胶片设置保留不丢，再打开就恢复。想要干净数码味、或只想用调色层修图时关它。

**1.2 胶片前曲线**

在胶片模拟之前作用的曲线，横轴/纵轴是曝光档（EV），中心 0 为不变。它改的是「送进胶片的场景明暗」，所以会连带影响负片曝光落点、颗粒与高光肩部——和调色里排在最后的成片曲线不是一层。先在这里压高光/提暗部，再让胶片去响应，比成片后再拉更自然。每个点位的输入/输出滑轨旁有复位按钮：输入复位回该点默认位置，输出复位回对角线（不变）。

## 2、画幅与配光

**1.1 胶片画幅**（135/36mm、645/56mm、6×6、6×7、6×8、6×9、6×12、6×17）
只告诉引擎这一格底片的物理长边多少毫米。引擎据此把颗粒直径、光晕扩散半径的微米数换算到成片上：片幅越大，同一强度的颗粒摊在更大画面上，出同一尺寸时颗粒更细、光晕更柔。它不改变曝光、色彩、对比、画面比例，所以不动颗粒和光晕时换画幅几乎看不出变化。

注意要分清它和「片边」里的画幅：这里的画幅是物理尺度（管颗粒、光晕的绝对大小），片边里的画幅是构图外框（管门径比例、齿孔排布、编号位置）。两个都叫画幅，但管的是两件事。

**1.2 配光读数**（一行只读文字）

`配光 自动 · EV −0.05 · 中性滤色 M 05 / Y 02`

- 自动/手动测光：当前是不是引擎在自动测光；
- EV：引擎为这张照片算出的曝光落点，只显示，不写回曝光补偿，滑轨仍是 0.0；
- M/Y：引擎算出的中性滤色包（品红、黄，单位 CC），就是你放大机滤色该拨到的位置；
- 若你手动拨过滤镜，末尾会追加「手动偏移 M +1.0 / Y −0.5」，提醒这张现在多了主观偏移。

读数在开图后自动测一次，只在胶片、相纸、测光方式、画幅、裁剪、曝光补偿、手动偏移变化时重算。同一张照片同样的设置，值永远一样——它不给新信息，只是让你看见引擎的落点。

**1.3 清除手动滤色偏移**

只把 M / Y 两个偏移归零，不碰曝光。这是原来「自动配光」按钮唯一还有实际用途的场景：你拨过滤镜、换了胶片、或者觉得画面偏了品红/黄，一键回到引擎的中性包。

## 3、曝光与测光

**2.1 曝光补偿**（−3 到 +3 EV）

叠加在引擎自动曝光之上的手动偏移。它改的是底片的曝光量，不是成片亮度：会连带影响颗粒可见度、高光肩部与暗部密度。±3 是刻意收紧的边界——再往外推，负片已经离开可用区，出来的是死黑死白而不是「更亮更暗」。

**2.2 测光方法**（均衡 / 中央重点 / 护高光 / 护阴影）

四种测光统计方式，决定引擎把哪块区域当成「中灰」：

- 均衡：全画面加权，最通用；
- 中央重点：中心权重高，主体曝光优先，背景亮暗不管；
- 护高光：把高光不溢出放在第一位，整体会偏暗一点；
- 护阴影：保证暗部有密度，整体偏亮，高光更容易顶。

换测光方法是少数能立刻看出差别、而且差别往往很大的操作。

**2.3 自动测光**（开关）

开着，引擎每帧自动落点，你只需要给偏移；关掉就是纯手动，曝光不再随画面内容自动修正。关掉后配光读数会标「手动测光」，那个 EV 只是拖动滑块的结果。

## 4、场景宽容度

这一组处理的是「场景的亮度范围超出介质能不能装下」这件事，不是调亮度。引擎先测出场景的亮度分布（p1 到 p99）和当前介质的真实宽容度区间（胶片 + 相纸 + 放大机），再算一条「置位曲线」，把场景两端压回介质能承受的范围内、尽量保住中间调对比。这条曲线默认是恒等映射——场景本来就装得下时，应用它一个像素都不会变。

**3.1 测量宽容度**（按钮）

点一下得到三行结果：

- 高光回拉 / 阴影回拉：建议把场景两端各压回多少 stop，都是 0 或负数说明不用动；
- 场景 p1 / p99：场景亮度的低位与高位分位点（stop），两者差值就是这张照片的实际动态范围；
- 介质宽容度 −x…+y stop：这套材料按实测能装下的区间，随胶片、相纸、放大机设置变，换材料要重测。

如果出现「场景两端都在介质内：无需置位，应用也不会改变画面」，就是明确告诉你这次不用做任何事——它是「告诉你需不需要压」，不是「点一下让画面变好看」。

如果显示「拟合失败 + 原因」，通常是画面太单一（大片纯色、大面积死黑死白、极端欠曝），测不出可信分布，此时不会给你应用按钮。

**3.2 应用场景置位**（按钮）

只有测量有效、且确实需要回拉时才出现。点它会把那条置位曲线写进参数：高光/暗部两端被压回介质范围，中间调对比基本保留。它属于冲印级的处理，排在颗粒、光晕之前。

## 5、相机白平衡（RAW）

只在 RAW 源上出现，因为它作用在解码阶段，改的是底片本身怎么被读出来。

**4.1 镜头校正**

按内置镜头库的配置文件做畸变、横向色差、暗角校正。面板会显示「已匹配镜头: xxx」或「未找到镜头配置，保留原始画面」。找不到配置时开关无效是正常的。它是几何校正，会改变画面边缘的取景，和裁剪是两件事。

**4.2 自定义白平衡 / 色温 K（2000–12000）/ 色调（±150）**

使用 Adobe DNG 的白平衡定义：Kelvin 定色温，tint 定绿—品红轴。开启后解码会按这组值重新解 RAW，三通道的原始数据被重新分配，所以它比调色里的色温/色调更彻底，也更「物理」。默认用拍摄时记录的白平衡（as-shot）。

**4.3 恢复拍摄白平衡**

把 Kelvin/tint 拉回相机记录的 as-shot 值，撤销你的自定义。调歪了不知道歪多少时，这是唯一可靠的复位。

## 6、镜头滤镜

**5.1 Wratten 彩色滤镜**（无 / W8 / W11 / W12 / W15 / W21 / W25 / W47 / W58）

装在镜头前、改变进入镜头光谱的物理滤镜，滤的是拍摄时的光，跟放大机的 Y/M 减色法、跟调色的色温都不是一层。它进引擎的解码/冲印路径，会实际改变三色通道的响应，所以颗粒、密度、反差都会跟着变，不是单纯加个色偏。

- W8（K2 浅黄）：轻微压蓝，天空略暗，黑白摄影最常用；
- W11（黄绿）：压蓝同时保绿，树叶与肤色不至于发死；
- W12（减蓝黄）：比 W8 更强，天空压得更深；
- W15（深黄）：强压蓝，云层与天空分离明显；
- W21（橙）：进一步压蓝，日落氛围、暖调人像；
- W25（红）：只放红与部分橙，蓝天几乎全黑，红外摄影的味道；
- W47（蓝）：只放蓝，压红黄，冷调分离；
- W58（绿）：放绿压红蓝，植物与肤色分离。

配黑白胶片时这类滤镜是「分离色」的正经手段；配彩色负片时它会留下明显偏色，通常要靠放大机滤色或调色再校回来。

## 7、放大机

**6.1 打印曝光**（0.25–4.00，左滑更暗、右滑更亮）

放大机镜头下的曝光时间系数，引擎按 2^(−EV) 换算，所以数值越小越亮，滑块做了反向映射。它改的是整张照片的密度，会影响颗粒可见度与高光肩部位置；和调色里的曝光不同，那个是成片加亮，颗粒不变。

**6.2 滤镜 Y（黄/蓝，±40CC）**

减色法放大机的黄滤色片，黄吸蓝。0 表示「不加主观偏移，用引擎算出的中性包」，拨动是在这个中性包上加偏移，不是替代它；所以换胶片后你原来的偏移会继续叠在新材料上，这就是配光读数里「手动偏移」要提示的东西。1.0 = 40CC。

**6.3 滤镜 M（品红/绿，±40CC）**

品红滤色片，品红吸绿。与 Y 相同，是叠加在中性包上的主观偏移量。

## 8、乳剂与暗房效应

这一组是整个 App 最「非常规」的部分，也是新手最容易乱动的地方。

**7.1 颗粒（总开关）**

关掉后整条颗粒模拟都不参与运算。

**7.2 颗粒强度**（0–上限×）

强度是按这卷胶片的固有颗粒能力折算的：1.00× 在细颗粒胶片（Ektar、Velvia）上比在高感卷（800T）上要细。滑块上限就是该胶片折算后引擎封顶 2.0 的位置，超出部分本来就不生效，所以被截掉了。看不出变化时，先看这个上限提示。

**7.3 分层颗粒**

真实乳剂是多层涂布，不同深度的卤化银晶体大小不同；开启后颗粒会呈现大颗粒套小颗粒的层次，关掉就是单层均匀噪点。差别在 100% 放大和大幅面打印时才明显。

**7.4 光晕强度 / 面积**

强光穿过乳剂后从片基背面反射回来，在亮部周围形成红色（彩色负片）或白色（黑白）的扩散光。有防光晕层时这一项叫「强度」，无背涂层的背反射模型下叫「面积」，控制的是扩散范围。

**7.5 光晕散射**

扩散的软硬。值大更糊更柔，值小扩散更紧、边界更清楚。

**7.6 光晕提升 EV**

只让超过某亮度的部分产生光晕，模拟只有高光才「打穿」乳剂。值越大，参与光晕的亮度门槛越低、范围越宽。

**7.7 保留防光晕层**

真胶片背面有一层防光晕涂层（AH layer），去掉它光晕会明显变强，CineStill 800T 这类去涂层卷就是这样。这里可以手动模拟「洗掉涂层」；选了无涂层卷时会自动锁定，不能反选。

**7.8 光晕模型（经典 / 背反射）**

前者是经验式红晕，后者按片基反射的物理几何算，面积与光圈相关，更接近实拍。

**7.9 余量 EV**（仅背反射模型）

控制反射回来的光有多少还能被乳剂记录，影响光晕的亮度上限。

**7.10 DIR 成色剂耦合 + DIR 强度**

显影时释放的抑制型成色剂会扩散到邻近层，压住邻区显影，形成边缘效应与细微的色彩分离（真实胶片细部反差和色彩「干净度」的来源之一）。强度 0 时画面会明显更平、更脏，1.0 附近最像正常冲洗。

**7.11 纸面光晕 + 强度**

相纸表面的涂层反射造成高光周边发亮扩散，RC 涂塑纸比钡地纸明显。它是成片之后的效应，跟前面的乳剂光晕不是一层。

**7.12 预闪**（0–0.03×）

底片在正式曝光前给一次极弱的均匀曝光，把暗部抬离阈值。效果是暗部细节出来、整体反差下降、最大密度略降。它是「减反差、保暗部」的物理手段，不是加亮度。

**7.13 扩展动态范围（EDR）**

把彩色负片的额外动态范围放出来，主要用于高光/暗部两头都吃紧的场景。只对彩色负片有效：反转片和黑白相纸的曲线是截断的，开了也不会有变化，面板上会直接说明不可用。这是它经常「点了没反应」的原因。

## 9、片边

**8.1 片边（整条胶片）**

总开关：打开后照片会被放进一条完整胶片带里，上下露出片边、齿孔、编号。

**8.2 画幅**

135、135 半格、135 Xpan、645、6×6、6×7、6×8、6×9、6×12、6×17。决定门径比例、齿孔排布、编号位置，也决定「片边文字」用哪套字样。

**8.3 片边模式**

strip（整条连续）或 filed（归档式，带裁切齿口的单格）。

**8.4 门形状**

square / rounded / eared / shouldered / kicked，模拟不同相机压片板与片门的实际轮廓，边角形状不同。

**8.5 齿孔**

white（透过片基看到的，正冲观片）或 black（印在纸上的，负片印相），取决于你把这条当成底片看还是当成照片看。

**8.6 边缘外**

none / black / open：片边之外是留白、压黑，还是让画面透出去。

**8.7 边缘雾化**

片边与画面交界的柔和过渡量。

**8.8 漏光**

片盒/后背密封不良的红色渗光。

**8.9 光圈（门边光晕）**

让门边的光晕随光圈值改变，大光圈时门边更亮。

**8.10 画幅编号**

滑轨 0-36，默认 0。**0 = 随机**：这一张在 1-36 里自己排一号，拖回 0 会再随机一次；**1-36 = 按设定输出**。原来的「按导入数量自动 36 帧一轮回递增」和「手动画幅编号开关」都删了。
单张导出就按上面这一号的规则输出。批量导出（点「导出所选照片」）会先统计这批里有几张开了片边，弹框确认后把这几张按勾选顺序从 01 开始重新连号，排到 36 回到 01 继续，照片够多就循环往复；没开片边的不参与重新编号。

**8.11 相机种子 / 过片种子**

滑轨 0-999，默认 0。**0 = 随机**：这一张自己抽一套（在 1-999 里），拖回 0 会再随机一次；**1-999 = 按设定输出**。相机种子决定机身那一侧（门形状、毛刺、边缘雾化），过片种子决定过片与扫描那一侧（漏光位置、编号抖动）。同样的种子得到同样的磨损，想把两张片的片边做成同一颗机身，就填同一个数。随机到的那一号会跟照片一起存进侧车，所以预览看到什么，导出就是什么。

## 10、日期后背

**9.1 日期后背（总开关）**

开启时导入就把这张照片的拍摄日期/参数填进去。日期先取原片 EXIF 的 DateTimeOriginal（没有再看 DateTimeDigitized）；EXIF 完全没有拍摄日期时退回相册记录的拍摄时间；两者都读不到才用系统当天，此时日期框下方会提示「照片未记录拍摄日期，请手动输入」。手填过的日期不会被自动覆盖。

**9.2 日期样式**

lcd（七段液晶）、dots（点阵）、data（只印一行拍摄参数，不印日期）。

**9.3 打印拍摄参数**

在日期下面多印一行 EXIF 摘要（相机、镜头、光圈快门 ISO）。EXIF 缺失时不会硬凑。

**9.4 位置**

frame（画面内角落）/ rebate（片边外）。只有开了片边且不是全景画幅时，片边位置才可用；全景画幅的片边不印日期。

**9.5 角落**

br / bl / tr / tl 四角之一。

**9.6 大小 / 曝光**

字号与印记亮度。曝光按 EV 给，值越高印记越亮，用来匹配底片不同密度区域的观感。

# 二、调色

## 1、白平衡

**1.1 色温（暖/冷，−1…+1）/ 色调（绿/品红，−1…+1）**

这是扫描白平衡，不是相机白平衡：对已经冲印出的成片做暖冷与绿/品红偏移。引擎不会因此重算底片，所以它修的是「这张照片的偏色」，不是「当时拍摄的光源」。真正改光源要在 RAW 的相机白平衡里做。

## 2、影调

**2.1 曝光**（−5…+5 EV）

按 EV 缩放成片。与冲印的打印曝光不是一层：这里颗粒、光晕、纸面都已经定型。

**2.2 对比度**（−100…+100）

绕中灰做 S 型拉伸，引擎系数约 1+1.2×值。左滑更平（发灰），右滑反差更大。

**2.3 亮度**（−100…+100）

中灰整体平移。看着像曝光，但影响高光截断的方式不同。

**2.4 高光 / 阴影**（各 −100…+100）

分区曲线：只压/提对应端，中间调基本不动。压高光救白墙细节，提阴影开暗部；拉过头会让画面发灰、失去密度感。

**2.5 饱和度**（−100…+100）

全通道等比加，容易把肤色推爆。想提色彩层次用「色彩混合」里的自然饱和度。

**2.6 黑点 / 白点**（各 −100…+100）

重设画面的黑白端。黑点往右压 = 暗部更实、反差更硬；往左抬 = 暗部发灰（做旧感）。白点往右提 = 高光更亮更透；往左收 = 高光变灰、更像低反差印相。这两个是控制「密度感」的关键，比对比度更精准。

## 3、曲线

**3.1 主曲线**

RGB 主曲线动明度与反差。它是最后一层，排在所有滑轨之后。

**3.2 单通道曲线**

R/G/B 各自一条，动色彩（例如蓝通道提暗部 = 阴影偏蓝）。

**3.3 点位滑轨与复位**

精确模式下每个点有输入/输出两条滑轨，旁边各带复位按钮：输入复位回该点的默认横位，输出复位回对角线（该点不变）。整条通道/全部曲线的复位在右上「更多」菜单里。

## 4、色彩混合

**4.1 自然饱和度（Vibrance）**

优先提低饱和的颜色，已经高饱和的少动，肤色受保护。与「影调」里的饱和度不是一回事。

**4.2 HSL 八色带（色相 / 饱和度 / 明度）**

对红、橙、黄、绿、青、蓝、紫、品红八段分别做色相旋转、饱和度、明度调整。明度改的是该色带的亮度轴，不改色相；调肤色通常动橙带，调植物动绿/黄带。

## 5、通道混合

**5.1 通道混合器**

输出通道由 R/G/B 三个输入加权组成，是做分色、假色、黑白滤镜效果的正经工具。例如三通道各吃自己的输入 = 恒等；把红通道设成「绿=1」就得到类似绿滤镜的黑白分离。它作用在冲印之后，不改变底片的物理响应。

## 6、色轮

**6.1 阴影 / 中间调 / 高光 色相偏移 + 强度**

用于三区分离调色（比如阴影压青、高光加暖）。和「色彩平衡」的六个滑轨是同一类思路，色轮给的是极坐标操作。

## 7、色彩平衡

**7.1 阴影 / 中间调 / 高光 × 色温 / 色调**

三区独立的暖冷与绿品红偏移，模拟彩色放大机三区校色。比色温滑块更可控，因为可以只动暗部而不动整张。

## 8、暗角

**8.1 强度**

压暗量。

**8.2 范围**

暗角从多靠内开始（左滑压到中间、右滑只压边角）。

**8.3 羽化**

过渡的软硬，左滑更硬、右滑更柔。只改边缘，不动中心曝光。

## 9、几何与裁剪

**9.1 旋转 / 翻转**

旋转按 90° 步进，水平/垂直翻转各自独立。

**9.2 拉直**

±45° 微调，用于地平线校正。

**9.3 自由裁剪**

进入画布操作。开了片边时裁剪不可用（片边的比例由画幅决定），这是刻意的。

**9.4 垂直 / 水平透视（各 ±30°）**

校正仰拍/俯拍造成的竖直线条汇聚（垂直），和侧拍造成的水平线条汇聚（水平）。它是对成片做梯形变换，会裁掉变换后空出的边，所以拉得越猛取景损失越大。两条滑轨各带复位按钮，下面还有「重置透视」一键归零。建筑、室内照最常用；普通照片动它反而容易歪。

**9.5 成片裁切（扳手菜单）**

在扳手菜单「裁剪」之后。和自由裁剪的区别：自由裁剪裁的是「底片取景」，会连带影响颗粒/光晕的物理尺度换算；成片裁切裁的是「已经洗出来的照片」，只切画面不改任何冲印参数。想二次构图又不想重算胶片效应时用它。裁切结果参与预览与导出，可随时取消恢复。

# 三、设置

**1、预览质量（长边 1024 / 1600 / 2048 px）**

预览渲染的长边上限。越小越快越省内存，颗粒等微结构在低预览下看不清属正常；导出成片不受它影响。

**2、默认胶片 / 默认相纸**

新照片的起始材料。每项都可以选「自动」或具体型号：

- 选具体型号：材料被锁定。导入/拍摄的新照片直接用它；「导入后自动显影」开着时也只调整影调（测光、对比、颗粒等），不再更换胶片相纸。
- 选「自动」：自动显影按画面内容挑胶片（自然/电影/复古三档各自的选片逻辑），相纸「自动」则跟随所选胶片的搭配纸。
- 优先级：已保存过编辑的照片 > 智能配方里选中的「我的配方」 > 这里的默认材料 > 自动选片。也就是说默认材料不会覆盖你手动存过的编辑，也不会覆盖你明确选中的配方。

这就是「默认材料」和「自动显影」的分工：一个定材料，一个定影调；两者不再互相打架。

**3、渲染缓存预算 / 清空渲染缓存**

可重新生成的临时渲染数据占用的磁盘上限。清空只删临时数据，不碰原图与已保存编辑。

**4、导出诊断报告（.zip）**

只含版本号、设备型号、当前设置与缓存统计，用于排查渲染异常；不含照片、文件名、路径、定位或日志，不自动上传。

# 四、导出与配方

**1、单张 / 批量导出**

批量按勾选的照片逐张导出，每张用自己的源文件名与自己的编辑；批量时「复制编辑设置」可先把当前调整套到其它张。

**2、文件格式（JPEG / PNG / TIFF / HEIF）**

JPEG 通用、体积可调；PNG 无损 8 bit；TIFF 16 bit 无损、可选 Deflate 压缩（体积更小仍无损）；HEIF 仅在本机编码器支持时出现，且只支持 sRGB 8 bit。

**3、分辨率 / 自定义尺寸**

长边 2048 / 2560 / 3840 / 原始 / 自定义。自定义可按长边、短边或像素总数（MP）限制，只缩不放大。大像素照片优先选 2048–3840，原始尺寸全量导出内存与等待都明显更大。

**4、色彩空间（sRGB / Display P3 / Adobe RGB / ProPhoto RGB）**

sRGB 兼容最广；其余三种把对应 ICC 写进文件（JPEG APP2 / PNG iCCP / TIFF tag34675），看图软件需支持色彩管理否则可能偏色。HEIF 固定 sRGB。

**5、质量 / Deflate**

JPEG/HEIF 质量 50–100%（默认 100，滑轨旁复位按钮回到 100）；TIFF 的 Deflate 为无损压缩开关。

**6、保留拍摄信息 / 保留位置信息**

拍摄信息复制相机、镜头、时间与曝光参数；位置信息只复制原片已有且可读取的 GPS。位置读取依赖导入那一刻的授权（见下），导入后才授权通常读不到。

**7、导出配方（保存 / 管理 / 当前配方）**

把「格式+分辨率+色彩空间+质量+保留开关+命名+压缩」存成一条导出配方，一键套用；管理弹窗可重命名/删除。它只管导出设置，不含调色参数。

**8、文件命名 / 保存位置（高级设置）**

命名按勾选顺序拼接原文件名/胶片/相纸/日期，分隔符可选；全不勾时沿用「原文件名_spektralab」。保存位置默认系统相册 Pictures/spektralab，也可指定任意文件夹。

**9、全屏预览（预览工具 · 放大检查成片）**

预览右上角绿色悬浮点展开工具（前后对比 / 全屏 / 收起），或点「查看原图」旁的放大图标进入全屏。全屏里**双指缩放**（最高 6 倍）、拖动查看细节，左上出现「回正 xx%」按钮一键复位。它只放大当前已渲染好的成片，不重新计算任何参数，所以很快；长按仍是查看原图。原「原尺寸细节 / DI TIFF / 软打样 / 高清预览」入口已隐藏（功能代码保留，不占界面）。

**10、我的配方：导入 / 导出（编辑配方弹窗）**

「我的配方」是调色/冲印参数模板（与导出配方不同）。弹窗底部可把全部我的配方导出为一个 JSON 文件备份或换机；导入时同名配方更新、新名字新增、坏记录跳过，不影响其它配方。智能配方里选中某条我的配方后，导入/拍摄的新照片也会先套它再按画面微调。

**11、导入后自动显影（智能配方开关）**

开着时导入/拍摄逐张分析自动套用；与默认材料的关系见「三、设置 2」。关掉则新照片用默认材料起始、完全手动。

**12、导出页的折叠结构**

导出页从上到下是四栏：文件格式、保留信息、导出配方、高级设置。点标题即展开/收起，收起时标题右侧直接显示当前取值（比如「JPEG · 原始尺寸 · sRGB · 质量100」），不用展开就能核对设置。四个格式按钮（JPEG/PNG/TIFF/HEIF）固定在栏头外面常显，切格式不用先点开。导出成功不再弹提示，直接看相册就行；批量导出因为耗时长，仍然会提示完成张数。

**13、导出成片的时间与位置**

成片在相册里的时间现在和原片一致。原因是 EXIF 的日期时间字符串本身不带时区标记，相册会按 UTC 记账，于是晚上拍的照片被显示成次日凌晨；现在导出时会把原片的时区偏移一起写进去（JPEG/PNG/HEIF/TIFF 四种格式都覆盖）。原片自带偏移的直接照抄，不改写时间本身。位置信息沿用上一条的规则：原片有就带上，原片没有就不写。已经导出过的旧成片不会被自动纠正，需要的话重导一次。

# 五、为什么很多参数看不出变化

1. 引擎本来就在自动配平：曝光和中性滤色自动解析，所以「自动配光」类操作常常什么都不改。
2. 参数被上限截断：颗粒强度到了该胶片的上限、滤镜到了 ±160CC 的物理范围，再推也不动。
3. 材料不支持：EDR 只对彩色负片；反转片/黑白相纸无效。
4. 预览分辨率与缓存：手机预览尺寸下，颗粒、光晕、纸面这类微结构本来就看不清，导出成片才看得出来。
5. 效应属于另一层：调色的色温改不了底片曝光；冲印的滤镜改不了成片白平衡。

